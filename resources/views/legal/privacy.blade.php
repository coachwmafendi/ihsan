    <p>Ihsan is a donation platform for Malaysian non-governmental organizations, operated from Malaysia. This page explains what we collect when someone gives through the platform, why we collect it, and who else sees it. Questions go to <a href="mailto:hello@getihsan.my">hello@getihsan.my</a>.</p>

    <h2>What we collect</h2>
    <p>When you make a donation we collect the details you type into the form: your name, email address, and — where the organization asks for them — your phone number and address. We record the donation itself: amount, currency, campaign, the organization receiving it, and whether it is one-time or recurring.</p>
    <p>We also record technical details of the request: your IP address, the device and browser you used, and the page you gave from. Where an organization has switched on advertising measurement, the form may also set identifiers supplied by that advertising network.</p>

    <h2>Card details</h2>
    <p>We never see or store your card number. Payments are handled by Stripe and by CHIP, who are licensed to process them; your card goes to them directly. What comes back to us is the card brand, its last four digits, its expiry month and year, and the country it was issued in — enough to show you which card a recurring gift will use, and no more.</p>

    <h2>Why we collect it</h2>
    <ul>
        <li>To take the donation and send you a receipt.</li>
        <li>To run a recurring plan: to charge it on schedule, to retry a failed installment, and to tell you when a card needs replacing.</li>
        <li>To check a payment for fraud. Your IP address and the country your card was issued in are part of that check.</li>
        <li>To decide which currency to offer you, from the country your request appears to come from.</li>
        <li>To report to the organization you gave to, so they can thank you and account for the funds.</li>
    </ul>

    <h2>Who else sees it</h2>
    <ul>
        <li><strong>The organization you gave to.</strong> They see your name, contact details, and your giving history with them. They do not see your card details.</li>
        <li><strong>Stripe and CHIP</strong>, who process the payment.</li>
        <li><strong>Amazon Web Services</strong>, who deliver our email.</li>
        <li><strong>Advertising networks</strong> — Meta, Google, LinkedIn, X or Snapchat — but only for organizations that have switched on advertising measurement, and only for donations made through their campaigns.</li>
    </ul>
    <p>We do not sell your details, and we do not share them with anyone else except where the law requires it.</p>

    <h2>How long we keep it</h2>
    <p>Donation records are kept for seven years, which is the period Malaysian tax and accounting rules expect of the organizations we serve. Technical records used for fraud checks are kept for two years. If you ask us to delete your details we will do so except where a record must be kept to meet those obligations.</p>

    <h2>Your choices</h2>
    <p>You may ask us for a copy of what we hold about you, ask us to correct it, or ask us to delete it. Every email we send carries a link to stop further email. To cancel a recurring gift, use the link in your receipt or ask the organization directly. Write to <a href="mailto:hello@getihsan.my">hello@getihsan.my</a> for any of these.</p>

    <h2>Changes to this policy</h2>
    <p>If this policy changes we will update the date at the top of this page. Donations already made are governed by the policy in force on the day they were made.</p>
